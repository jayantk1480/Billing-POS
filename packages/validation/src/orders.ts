import { z } from 'zod';
import { isoDateSchema, mobileSchema, nullableText, pageQuerySchema, paiseSchema, pinSchema, sortDirectionSchema, text, uuidSchema } from './common.js';
import { stateCodeSchema } from './restaurant.js';

export const orderTypeSchema = z.enum(['DINE_IN', 'TAKEAWAY', 'DELIVERY']);
export type OrderType = z.infer<typeof orderTypeSchema>;
export const orderStatusSchema = z.enum(['OPEN', 'HELD', 'BILLED', 'SETTLED', 'CANCELLED', 'MERGED']);
export type OrderStatus = z.infer<typeof orderStatusSchema>;
export const paymentMethodSchema = z.enum(['CASH', 'UPI', 'CARD', 'OTHER']);
export type PaymentMethod = z.infer<typeof paymentMethodSchema>;

const dateSchema = isoDateSchema;

export const discountInputSchema = z
  .object({
    type: z.enum(['PERCENT', 'AMOUNT']),
    /** Basis points for PERCENT (1000 = 10%), paise for AMOUNT. */
    value: z.number('Enter a discount').int('Enter a valid discount').min(1, 'Enter a discount').max(2_000_000_000),
    reason: nullableText(200),
  })
  .refine((discount) => discount.type !== 'PERCENT' || discount.value <= 10_000, { path: ['value'], message: 'A discount cannot exceed 100%' });
export type DiscountInput = z.input<typeof discountInputSchema>;

/** A manager's sign-off for an action the signed-in user is not allowed to do alone. */
export const approvalSchema = z.object({ userId: uuidSchema, pin: pinSchema });
export type ApprovalInput = z.infer<typeof approvalSchema>;

/** The mobile number is what identifies a customer: one number, one customer. The name is for the bill. */
export const customerInputSchema = z.object({
  phone: mobileSchema,
  name: nullableText(80),
  address: nullableText(300),
});
export type CustomerInput = z.input<typeof customerInputSchema>;

export const orderItemInputSchema = z.object({
  /** Generated by the POS, so the same line keeps its identity across saves. */
  id: uuidSchema,
  productId: uuidSchema,
  variantId: uuidSchema.nullish(),
  modifierIds: z.array(uuidSchema).max(20).default([]),
  quantity: z.number().int().min(1, 'Quantity must be at least 1').max(999),
  notes: nullableText(200),
  discount: discountInputSchema.nullish(),
});
export type OrderItemInput = z.input<typeof orderItemInputSchema>;

export const saveOrderSchema = z
  .object({
    type: orderTypeSchema,
    tableId: uuidSchema.nullish(),
    guests: z.number().int().min(1).max(99).default(1),
    notes: nullableText(300),
    deliveryAddress: nullableText(300),
    customer: customerInputSchema.nullish(),
    /** The full list of lines: lines missing from the list are removed. */
    items: z.array(orderItemInputSchema).max(200),
    discount: discountInputSchema.nullish(),
    approval: approvalSchema.optional(),
    /** Why items already sent to the kitchen are being reduced or removed. Required when that happens. */
    kotCancelReason: nullableText(200),
    /** The version the POS last saw. A mismatch means another terminal changed the order. */
    version: z.number().int().optional(),
  })
  .refine((order) => order.type !== 'DINE_IN' || Boolean(order.tableId), { path: ['tableId'], message: 'Choose a table for a dine-in order' });
export type SaveOrderInput = z.input<typeof saveOrderSchema>;

export const reasonSchema = z.object({ reason: text(200, 'Reason'), approval: approvalSchema.optional() });
export type ReasonInput = z.input<typeof reasonSchema>;

/** A change to an order that already has a bill: the new lines, and how the new total was paid. */
export const amendOrderSchema = z.object({
  /** The full list of lines, as when an open order is saved. */
  items: z.array(orderItemInputSchema).min(1, 'An order needs at least one item. To remove it altogether, delete the order.').max(200),
  discount: discountInputSchema.nullish(),
  /**
   * What happens to the money. An object records the new total as paid in full by that method.
   * "KEEP" carries over the payments already received as they are, leaving any difference due.
   * Leave out to leave the new bill unpaid.
   */
  payment: z.union([z.literal('KEEP'), z.object({ method: paymentMethodSchema, reference: nullableText(60) })]).nullish(),
  reason: text(200, 'Reason'),
  approval: approvalSchema.optional(),
});
export type AmendOrderInput = z.input<typeof amendOrderSchema>;

export const mergeOrderSchema = z.object({ sourceOrderId: uuidSchema });

export const issueInvoicesSchema = z.object({
  /**
   * Split by item: each part becomes its own invoice. Together the parts must cover every
   * line's full quantity. Omit to issue one invoice for the whole order.
   */
  parts: z
    .array(z.array(z.object({ orderItemId: uuidSchema, quantity: z.number().int().min(1).max(999) })).min(1))
    .min(2, 'A split needs at least two bills')
    .max(10)
    .optional(),
  /** GST state code of the place of supply. Defaults to the restaurant's own state. */
  placeOfSupply: stateCodeSchema.optional(),
  /**
   * Ids the POS gives the bills: one per part, or one for a bill that is not split. Sending the same ids again
   * returns the bills already issued under them instead of failing, so a bill whose answer was lost on a weak
   * connection can simply be asked for again. Leave out to let the server choose.
   */
  invoiceIds: z.array(uuidSchema).min(1).max(10).optional(),
}).refine((input) => !input.invoiceIds || input.invoiceIds.length === (input.parts?.length ?? 1), {
  path: ['invoiceIds'], message: 'Give one bill id for each part of the bill',
}).refine((input) => !input.invoiceIds || new Set(input.invoiceIds).size === input.invoiceIds.length, {
  path: ['invoiceIds'], message: 'The same bill id was given twice',
});
export type IssueInvoicesInput = z.input<typeof issueInvoicesSchema>;

export const paymentInputSchema = z.object({
  /** Generated by the POS. Sending the same id again never records a second payment. */
  id: uuidSchema,
  method: paymentMethodSchema,
  amountPaise: paiseSchema.min(1, 'Enter an amount'),
  /** Cash handed over, when more than the amount; the difference is the change to return. */
  tenderedPaise: paiseSchema.optional(),
  reference: nullableText(60),
});
export type PaymentInput = z.input<typeof paymentInputSchema>;

export const recordPaymentsSchema = z.object({ payments: z.array(paymentInputSchema).min(1).max(10) });
export type RecordPaymentsInput = z.input<typeof recordPaymentsSchema>;

export const refundInputSchema = z
  .object({
    /** Generated by the POS. Sending the same id again never issues a second refund. */
    id: uuidSchema,
    /** The payment the money goes back against. */
    paymentId: uuidSchema,
    amountPaise: paiseSchema.min(1, 'Enter an amount').optional(),
    /** Refund specific items instead of an amount. */
    items: z.array(z.object({ invoiceItemId: uuidSchema, quantity: z.number().int().min(1).max(999) })).min(1).max(200).optional(),
    reason: text(200, 'Reason'),
    approval: approvalSchema.optional(),
  })
  .refine((refund) => (refund.amountPaise === undefined) !== (refund.items === undefined), {
    path: ['amountPaise'],
    message: 'Give either an amount or the items to refund',
  });
export type RefundInput = z.input<typeof refundInputSchema>;

export const cancelInvoiceSchema = z.object({
  reason: text(200, 'Reason'),
  /** Put the order back into editing so it can be corrected and billed again. */
  reopenOrder: z.boolean().default(false),
  approval: approvalSchema.optional(),
});
export type CancelInvoiceInput = z.input<typeof cancelInvoiceSchema>;

/** Correcting how a payment already recorded was made. The amount is not part of it. */
export const changePaymentMethodSchema = z.object({
  method: paymentMethodSchema,
  /** UPI transaction id, card slip number and the like, for the new method. */
  reference: nullableText(60),
  reason: text(200, 'Reason'),
});
export type ChangePaymentMethodInput = z.input<typeof changePaymentMethodSchema>;

export const orderQuerySchema = pageQuerySchema.extend({
  status: orderStatusSchema.optional(),
  type: orderTypeSchema.optional(),
  from: dateSchema.optional(),
  to: dateSchema.optional(),
  search: z.string().trim().max(60).optional(),
  /** The column to sort by. Left out, the newest orders come first. */
  sort: z.enum(['order', 'date', 'type', 'takenBy', 'bill', 'billingType', 'total', 'status']).optional(),
  direction: sortDirectionSchema,
});
export type OrderQuery = z.input<typeof orderQuerySchema>;

export const invoiceQuerySchema = pageQuerySchema.extend({
  status: z.enum(['ISSUED', 'CANCELLED']).optional(),
  paymentStatus: z.enum(['UNPAID', 'PARTIALLY_PAID', 'PAID', 'PARTIALLY_REFUNDED', 'REFUNDED']).optional(),
  from: dateSchema.optional(),
  to: dateSchema.optional(),
  search: z.string().trim().max(60).optional(),
  /** The column to sort by. Left out, the newest bills come first. */
  sort: z.enum(['bill', 'issued', 'order', 'customer', 'cashier', 'total', 'paid', 'status']).optional(),
  direction: sortDirectionSchema,
});
export type InvoiceQuery = z.input<typeof invoiceQuerySchema>;

// ── Responses ──

export interface DiscountDto {
  type: 'PERCENT' | 'AMOUNT';
  value: number;
  reason: string | null;
  amountPaise: number;
}

/**
 * The customer as an order or bill carries them. A bill issued before mobile numbers were required may have no number,
 * and one issued before GSTINs were taken off customers may carry one; new bills never do.
 */
export interface CustomerDto {
  name: string | null;
  phone: string | null;
  gstin: string | null;
  address: string | null;
}

export interface OrderItemDto {
  id: string;
  productId: string;
  variantId: string | null;
  name: string;
  variantName: string | null;
  modifiers: { id: string; name: string; pricePaise: number }[];
  quantity: number;
  /** How many of these the kitchen has already been told about. */
  kotQuantity: number;
  unitPricePaise: number;
  notes: string | null;
  /** Needed by the POS to re-price the order locally while it is being edited. */
  taxGroupId: string | null;
  priceIncludesTax: boolean;
  discount: DiscountDto | null;
  grossPaise: number;
  discountPaise: number;
  taxablePaise: number;
  taxPaise: number;
  totalPaise: number;
}

export interface BillTotals {
  grossPaise: number;
  discountPaise: number;
  taxPaise: number;
  serviceChargePaise: number;
  roundOffPaise: number;
  totalPaise: number;
}

export interface InvoiceSummaryDto {
  id: string;
  invoiceNumber: string;
  status: 'ISSUED' | 'CANCELLED';
  paymentStatus: 'UNPAID' | 'PARTIALLY_PAID' | 'PAID' | 'PARTIALLY_REFUNDED' | 'REFUNDED';
  totalPaise: number;
  paidPaise: number;
  refundedPaise: number;
}

export interface OrderDto {
  id: string;
  /** Display number such as "A1-12". Renumbered when an earlier unbilled order is deleted. */
  displayNumber: string;
  series: string;
  orderNumber: number;
  /** The number given to the customer when the order was taken. Never changes. */
  tokenNumber: number | null;
  businessDate: string;
  type: OrderType;
  status: OrderStatus;
  tableId: string | null;
  tableName: string | null;
  guests: number;
  notes: string | null;
  deliveryAddress: string | null;
  customer: CustomerDto | null;
  items: OrderItemDto[];
  discount: DiscountDto | null;
  totals: BillTotals;
  invoices: InvoiceSummaryDto[];
  /** How the order was paid: the methods of the payments on its bills, in a fixed order. Empty until money is taken. */
  paymentMethods: PaymentMethod[];
  createdByName: string;
  cancelReason: string | null;
  version: number;
  createdAt: string;
  updatedAt: string;
}

/** One row of an order list: everything except the lines. */
export type OrderSummaryDto = Omit<OrderDto, 'items' | 'discount' | 'customer'> & { itemCount: number; customerName: string | null; customerPhone: string | null };

export interface InvoiceItemDto {
  id: string;
  name: string;
  hsnSac: string | null;
  quantity: number;
  unitPricePaise: number;
  grossPaise: number;
  discountPaise: number;
  taxablePaise: number;
  taxRateBps: number;
  cgstPaise: number;
  sgstPaise: number;
  igstPaise: number;
  cessPaise: number;
  totalPaise: number;
  /** Quantity already returned through refunds. */
  refundedQuantity: number;
}

export interface PaymentDto {
  id: string;
  method: PaymentMethod;
  status: 'PENDING' | 'SUCCESS' | 'FAILED' | 'CANCELLED';
  amountPaise: number;
  tenderedPaise: number | null;
  changePaise: number | null;
  refundedPaise: number;
  reference: string | null;
  receivedByName: string;
  paidAt: string | null;
}

export interface RefundDto {
  id: string;
  creditNoteNumber: string;
  paymentId: string | null;
  method: PaymentMethod;
  amountPaise: number;
  reason: string;
  createdByName: string;
  createdAt: string;
}

export interface SellerDto {
  name: string;
  legalName: string | null;
  gstin: string | null;
  fssaiNumber: string | null;
  phone: string | null;
  addressLines: string[];
  stateCode: string;
  stateName: string;
  footer: string | null;
  upiVpa: string | null;
}

